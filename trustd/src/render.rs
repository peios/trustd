    /// Check the bytes in every artifact, not just the comments or names.
    /// The two synthetic fixtures deliberately have the same subject hash.
    fn assert_purpose_artifacts(root: &Path, composed: &Composed, expected: &[&str]) {
        let mut expected_der: Vec<Vec<u8>> = expected
            .iter()
            .map(|pem| cert::from_pem(pem).remove(0))
            .collect();
        expected_der.sort();
        let text = fs::read_to_string(root.join("certs/ca-certificates.crt")).unwrap();
        assert_eq!(fs::read_to_string(root.join("cert.pem")).unwrap(), text);
        assert_eq!(bundle(composed), text);
        let mut bundle_der = cert::from_pem(&text);
        bundle_der.sort();
        assert_eq!(bundle_der, expected_der, "the PEM bundle's exact DER set");

        let added = usize::from(expected.contains(&PURPOSE_ADDED));
        let shipped = expected.len() - added;
        assert!(text.contains(&format!(
            "# {} root(s): {shipped} shipped, {added} added.",
            expected.len()
        )));

        let hash = cert::parse(&cert::from_pem(PURPOSE_SHIPPED)[0], None)
            .unwrap()
            .subject_hash;
        assert_eq!(
            cert::parse(&cert::from_pem(PURPOSE_ADDED)[0], None)
                .unwrap()
                .subject_hash,
            hash
        );
        let mut names: Vec<_> = fs::read_dir(root.join("certs"))
            .unwrap()
            .map(|entry| entry.unwrap().file_name().into_string().unwrap())
            .collect();
        names.sort();
        let mut expected_names = vec!["ca-certificates.crt".to_owned()];
        let mut hashed_der = Vec::new();
        for sequence in 0..expected.len() {
            let name = format!("{hash}.{sequence}");
            let pem = fs::read_to_string(root.join("certs").join(&name)).unwrap();
            let mut certificates = cert::from_pem(&pem);
            assert_eq!(certificates.len(), 1);
            hashed_der.push(certificates.remove(0));
            expected_names.push(name);
        }
        expected_names.sort();
        hashed_der.sort();
        assert_eq!(names, expected_names, "no stale or extra hashed files");
        assert_eq!(hashed_der, expected_der, "the CApath's exact DER set");
        assert!(!root.join("certs.new").exists());
        assert!(!root.join("certs.previous").exists());
    }

