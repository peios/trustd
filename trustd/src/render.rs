//! Rendering the compat files.
//!
//! The socket is the store; these files are a compatibility artifact of it,
//! for the software that reads trust from a path — which today is nearly all
//! of it. `GenerateLinuxTrustFiles` decides whether they exist at all.
//!
//! Three artifacts, because this build of OpenSSL is configured
//! `--openssldir=/etc/ssl` and the ecosystem is not of one mind:
//!
//! | Path | Who reads it |
//! |---|---|
//! | `certs/ca-certificates.crt` | Go probes it first; most software is configured with it |
//! | `cert.pem` | OpenSSL's default `CAfile` for this build |
//! | `certs/<subject-hash>.<n>` | OpenSSL's default `CApath` |
//!
//! The hashed directory is not decoration. A `CApath` lookup that finds a
//! stale file for a distrusted root would keep trusting it, so the directory
//! is replaced **atomically**: the new one is built alongside and exchanged
//! in a single syscall. There is no moment at which the directory holds a
//! mixture of the old set and the new.

use std::fs;
use std::io;
use std::io::ErrorKind;
use std::os::unix::ffi::OsStrExt;
use std::os::unix::fs::PermissionsExt;
use std::path::Path;

use crate::cert;
use crate::store::{self, Composed, Entry};

/// `GenerateLinuxTrustFiles`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Compat {
    /// No files. The pure-native machine: everything asks the socket, and
    /// software that reads a path fails — visibly, with certificate errors.
    None,
    /// Rendered and kept current. The default, and what every image ships
    /// until its whole software set speaks the socket.
    #[default]
    Files,
    /// Reserved: the files served through trustd itself, per read. Treated
    /// as `Files` until it exists, if it ever does.
    Live,
}

impl Compat {
    pub fn from_dword(value: u32) -> Compat {
        match value {
            0 => Compat::None,
            2 => Compat::Live,
            _ => Compat::Files,
        }
    }

    pub fn as_dword(self) -> u32 {
        match self {
            Compat::None => 0,
            Compat::Files => 1,
            Compat::Live => 2,
        }
    }
}

const FILE_MODE: u32 = 0o644;
const DIR_MODE: u32 = 0o755;

/// The bundle's provenance header. A person opening the file should be able
/// to tell where it came from and that editing it is pointless.
fn header(roots: &[&Entry]) -> String {
    format!(
        "# Peios trust store — generated by trustd; edits are overwritten.\n\
         #\n\
         # This file is a compatibility rendering of the machine's trust store.\n\
         # It is composed from the roots the ca-certificates package ships and\n\
         # the additions and distrusts under Machine\\System\\Trust\\Certificates.\n\
         # To change what this machine trusts, use `trust add` / `trust distrust`\n\
         # or write the registry directly — never this file.\n\
         #\n\
         # {} root(s): {} shipped, {} added.\n\n",
        roots.len(),
        roots
            .iter()
            .filter(|r| r.source == libtrust::Source::Shipped)
            .count(),
        roots
            .iter()
            .filter(|r| r.source == libtrust::Source::Added)
            .count(),
    )
}

/// The compatibility bundle: ServerAuth roots, each with a comment naming it.
pub fn bundle(composed: &Composed) -> String {
    bundle_for_roots(&store::for_purpose(&composed.roots, store::SERVER_AUTH))
}

fn bundle_for_roots(roots: &[&Entry]) -> String {
    let mut out = header(roots);
    for root in roots {
        out.push_str(&format!("# {}\n", root.parsed.subject));
        if let Some(name) = &root.name {
            out.push_str(&format!("# added as {name}\n"));
        }
        out.push_str(&format!("# SHA-256 {}\n", root.parsed.fingerprint));
        out.push_str(&cert::to_pem(&root.parsed.der));
        out.push('\n');
    }
    out
}

/// Add the operation and the path to an error. A renderer does a dozen
/// filesystem operations and reports one error; without this, "Permission
/// denied" says nothing about what was denied.
fn at<'a>(operation: &'a str, path: &'a Path) -> impl FnOnce(io::Error) -> io::Error + 'a {
    move |e| io::Error::new(e.kind(), format!("{operation} {}: {e}", path.display()))
}

/// Write the files for `composed` under `root`, or remove them in
/// [`Compat::None`]. Returns the paths that now exist.
///
/// `root` is the store directory (`/system/retc/ssl` in production, a
/// temporary directory in tests).
pub fn render(root: &Path, composed: &Composed, compat: Compat) -> io::Result<Vec<String>> {
    let certs = root.join("certs");
    let cert_pem = root.join("cert.pem");

    if compat == Compat::None {
        // Leaving the files behind would leave stale trust in force, which
        // is worse than the honest breakage of having none. The directories
        // themselves stay: they are the hook's, and an empty CApath is
        // exactly as trust-free as an absent one.
        remove_if_present(&cert_pem).map_err(at("remove", &cert_pem))?;
        if certs.exists() {
            empty_dir(&certs).map_err(at("empty", &certs))?;
        }
        return Ok(Vec::new());
    }

    fs::create_dir_all(root).map_err(at("create", root))?;
    set_mode(root, DIR_MODE);

    // Build the whole directory alongside, then exchange it in one step.
    //
    // The staging directory is emptied and refilled, never created and
    // destroyed. On Peios a directory a service creates for itself comes
    // out with a descriptor that names SYSTEM and Administrators and not
    // the creator, so a least-privileged daemon can make a directory it
    // cannot then use. Both directories are made once by the pre-start
    // hook, and a rename carries a descriptor with it — so exchanging them
    // for ever keeps the grant that was stamped on each.
    let staging = root.join("certs.new");
    if staging.exists() {
        empty_dir(&staging).map_err(at("empty", &staging))?;
    } else {
        fs::create_dir_all(&staging).map_err(at("create", &staging))?;
        set_mode(&staging, DIR_MODE);
    }

    // Keep every compatibility artifact on the same purpose-filtered set.
    // The full composition remains available to purpose-aware socket clients.
    let roots = store::for_purpose(&composed.roots, store::SERVER_AUTH);
    let text = bundle_for_roots(&roots);
    let bundle_path = staging.join("ca-certificates.crt");
    write_file(&bundle_path, text.as_bytes()).map_err(at("write", &bundle_path))?;

    // OpenSSL's CApath: one PEM per root, named by subject hash, with a
    // sequence number to separate the occasional collision.
    let mut used: Vec<(String, u32)> = Vec::new();
    for root_entry in roots {
        let hash = &root_entry.parsed.subject_hash;
        let sequence = match used.iter_mut().find(|(h, _)| h == hash) {
            Some((_, n)) => {
                *n += 1;
                *n
            }
            None => {
                used.push((hash.clone(), 0));
                0
            }
        };
        let hashed = staging.join(format!("{hash}.{sequence}"));
        write_file(&hashed, cert::to_pem(&root_entry.parsed.der).as_bytes())
            .map_err(at("write", &hashed))?;
    }

    exchange(&staging, &certs).map_err(at("install", &certs))?;

    // The default CAfile is a copy rather than a link: it is read through a
    // filesystem merge, and a plain file has no resolution to get wrong.
    write_file(&cert_pem, text.as_bytes()).map_err(at("write", &cert_pem))?;

    Ok(vec![
        certs.join("ca-certificates.crt").display().to_string(),
        cert_pem.display().to_string(),
        certs.display().to_string(),
    ])
}

/// Write a file whole or not at all: a reader never sees a partial store.
fn write_file(path: &Path, contents: &[u8]) -> io::Result<()> {
    let temporary = path.with_extension("tmp");
    fs::write(&temporary, contents)?;
    set_mode(&temporary, FILE_MODE);
    fs::rename(&temporary, path)
}

/// Best-effort, and deliberately so. On Peios access is decided by the
/// security descriptor — which trustd stamps separately — not by mode bits,
/// and `chmod` may not be permitted at all. A render that failed over a
/// permission bit nothing consults would leave the machine with no trust
/// store for no reason. The mode still matters when these files are read on
/// an ordinary Linux host, so it is set where it can be.
fn set_mode(path: &Path, mode: u32) {
    let _ = fs::set_permissions(path, fs::Permissions::from_mode(mode));
}

fn remove_if_present(path: &Path) -> io::Result<()> {
    match fs::remove_file(path) {
        Ok(()) => Ok(()),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(()),
        Err(e) => Err(e),
    }
}

/// Remove a directory's contents, leaving the directory — and its
/// descriptor — in place.
fn empty_dir(path: &Path) -> io::Result<()> {
    for entry in fs::read_dir(path)? {
        let entry = entry?;
        if entry.file_type()?.is_dir() {
            fs::remove_dir_all(entry.path())?;
        } else {
            fs::remove_file(entry.path())?;
        }
    }
    Ok(())
}

fn remove_dir_if_present(path: &Path) -> io::Result<()> {
    match fs::remove_dir_all(path) {
        Ok(()) => Ok(()),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(()),
        Err(e) => Err(e),
    }
}

/// Put `staging` where `live` is, atomically, and remove what was there.
///
/// `RENAME_EXCHANGE` swaps the two directories in one syscall, so no reader
/// ever sees the directory absent, half-built, or holding a mixture of the
/// old roots and the new. When `live` does not exist yet there is nothing to
/// exchange with and a plain rename is atomic on its own.
fn exchange(staging: &Path, live: &Path) -> io::Result<()> {
    if !live.exists() {
        return fs::rename(staging, live);
    }
    let from = cstring(staging)?;
    let to = cstring(live)?;
    // SAFETY: both paths are live NUL-terminated strings for the call.
    let rc = unsafe {
        libc::renameat2(
            libc::AT_FDCWD,
            from.as_ptr(),
            libc::AT_FDCWD,
            to.as_ptr(),
            libc::RENAME_EXCHANGE,
        )
    };
    if rc != 0 {
        // Note: on the failure path below the directories are renamed
        // rather than recreated, so their descriptors travel with them.
        let error = io::Error::last_os_error();
        // A filesystem without RENAME_EXCHANGE (or a kernel that lacks the
        // syscall) still gets a correct store, just with a window in which
        // the directory is the new one before the old is gone. Better than
        // refusing to render.
        if matches!(
            error.raw_os_error(),
            Some(libc::EINVAL) | Some(libc::ENOSYS) | Some(libc::ENOTSUP)
        ) || error.kind() == ErrorKind::PermissionDenied
        {
            let previous = live.with_extension("previous");
            remove_dir_if_present(&previous)?;
            fs::rename(live, &previous)?;
            fs::rename(staging, live)?;
            return remove_dir_if_present(&previous);
        }
        return Err(error);
    }
    remove_dir_if_present(staging)
}

fn cstring(path: &Path) -> io::Result<std::ffi::CString> {
    std::ffi::CString::new(path.as_os_str().as_bytes())
        .map_err(|_| io::Error::new(io::ErrorKind::InvalidInput, "path holds a NUL"))
}

/// The store directory's files, for a status reply.
pub fn rendered_paths(root: &Path) -> Vec<String> {
    let mut out = Vec::new();
    for path in [
        root.join("certs").join("ca-certificates.crt"),
        root.join("cert.pem"),
    ] {
        if path.exists() {
            out.push(path.display().to_string());
        }
    }
    out
}

/// A stable identity for the shipped bundle, so a package upgrade is noticed
/// without watching for filesystem events: its length and modification time.
pub fn stamp(path: &Path) -> Option<(u64, i64)> {
    let meta = fs::metadata(path).ok()?;
    let modified = meta
        .modified()
        .ok()?
        .duration_since(std::time::UNIX_EPOCH)
        .ok()?
        .as_secs() as i64;
    Some((meta.len(), modified))
}

